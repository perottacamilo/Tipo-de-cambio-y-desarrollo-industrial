traducir_pais_wdi <- function(x) {
  x <- as.character(x)
  indices <- match(x, names(paises_wdi_espanol))
  sin_traduccion <- !is.na(x) & is.na(indices)

  if (any(sin_traduccion)) {
    stop(
      "No hay traducción WDI para: ",
      paste(unique(x[sin_traduccion]), collapse = ", "),
      call. = FALSE
    )
  }

  unname(paises_wdi_espanol[indices])
}
